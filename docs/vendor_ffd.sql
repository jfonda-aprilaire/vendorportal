-- Field layouts for the Vendor Inquiry files, as one result set.
-- Run in VS Code (Code for IBM i SQL) or ACS Run SQL Scripts. Use one session:
-- QTEMP only lives for the job.

-- 1. Dump field definitions to an outfile (first one replaces, rest append)
CALL QSYS2.QCMDEXC('DSPFFD FILE(RPCLIB/MC.SVMM) OUTPUT(*OUTFILE) OUTFILE(QTEMP/FFD)');
CALL QSYS2.QCMDEXC('DSPFFD FILE(RPCLIB/MC.SVEM) OUTPUT(*OUTFILE) OUTFILE(QTEMP/FFD) OUTMBR(*FIRST *ADD)');
CALL QSYS2.QCMDEXC('DSPFFD FILE(RPCLIB/MCSVFX) OUTPUT(*OUTFILE) OUTFILE(QTEMP/FFD) OUTMBR(*FIRST *ADD)');
CALL QSYS2.QCMDEXC('DSPFFD FILE(RPCLIB/MCSVEMLAA) OUTPUT(*OUTFILE) OUTFILE(QTEMP/FFD) OUTMBR(*FIRST *ADD)');
CALL QSYS2.QCMDEXC('DSPFFD FILE(RPCLIB/MC.SVEMA) OUTPUT(*OUTFILE) OUTFILE(QTEMP/FFD) OUTMBR(*FIRST *ADD)');
CALL QSYS2.QCMDEXC('DSPFFD FILE(RPCLIB/ORCARRLB) OUTPUT(*OUTFILE) OUTFILE(QTEMP/FFD) OUTMBR(*FIRST *ADD)');

-- 2. One row per field, with byte positions to match against MCS700_field_map.md
SELECT WHLIB   AS LIB,
       WHFILE  AS FILE,
       WHNAME  AS RCDFMT,
       WHFLDE  AS FIELD,
       WHIBO   AS FROM_POS,
       WHIBO + WHFLDB - 1 AS TO_POS,
       WHFLDT  AS TYPE,
       WHFLDB  AS BYTES,
       WHFLDD  AS DIGITS,
       WHFLDP  AS DEC,
       WHFTXT  AS TEXT
  FROM QTEMP.FFD
 ORDER BY WHFILE, WHIBO;

-- 3. Where the email LF and carrier file live, and the PF behind MCSVEMLAA
--    Dotted S/36 names need their own pattern. Live email PF = RPCLIB/MC.SVEMA (MC.SVEMAX is a leftover).
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE, TABLE_TEXT
  FROM QSYS2.SYSTABLES
 WHERE TABLE_NAME LIKE 'MCSVEM%'
    OR TABLE_NAME LIKE 'MC.SVEM%'
    OR TABLE_NAME LIKE 'MCSVED%'
    OR TABLE_NAME LIKE 'ORCARR%'
 ORDER BY TABLE_NAME;
